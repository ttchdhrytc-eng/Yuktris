-- ============================================================
-- Trigger: auto-update updated_at on prospect_discovery
-- ============================================================

CREATE OR REPLACE FUNCTION update_prospect_discovery_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_prospect_discovery_updated_at ON prospect_discovery;
CREATE TRIGGER trigger_prospect_discovery_updated_at
  BEFORE UPDATE ON prospect_discovery
  FOR EACH ROW
  EXECUTE FUNCTION update_prospect_discovery_updated_at();
